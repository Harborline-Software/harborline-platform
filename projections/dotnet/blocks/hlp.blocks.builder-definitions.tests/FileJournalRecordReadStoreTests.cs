    [Fact]
    public async Task the_real_journal_reads_only_committed_exact_tenant_record_id_and_detaches_each_body()
    {
        var store = new FileJournalRecordWriteStore(PathName);
        Assert.Null(await store.FindAsync(Tenant, "Record-7")); // Missing directory keeps existing empty behavior.
        await using var first = await Stage(store, Row("Record-7", "operation-a", new("schema:fixture")));
        Assert.Null(await store.FindAsync(Tenant, "Record-7"));
        Assert.Equal(RecordWriteCommitDisposition.Created, (await first.CommitAsync()).Disposition);
        await using var other = await Stage(store, Row("Record-7", "operation-b", new("schema:other")) with { Tenant = "tenant-b" });
        await other.CommitAsync();
        IRecordReadStore reopened = new FileJournalRecordWriteStore(PathName);
        var row = Assert.IsType<RecordWriteRow>(await reopened.FindAsync("tenant-a", "Record-7"));
        Assert.Equal("operation-a", row.OperationId);
        Assert.Equal("eam.reading", row.RecordTypeId);
        Assert.Equal("1.0.0", row.Version);
        Assert.Equal(TypeDigest, row.DefinitionDigest);
        Assert.Equal("schema:fixture", row.Schema.Value);
        Assert.Equal("{\"value\":\"A\"}", Encoding.UTF8.GetString(row.Body.Span));
        Assert.Equal(new DateTimeOffset(2026, 2, 3, 4, 5, 6, TimeSpan.Zero), row.RecordedAt);
        Assert.Equal("schema:other", (await reopened.FindAsync("tenant-b", "Record-7"))!.Schema.Value);
        foreach (var (tenant, id) in new[] { ("TENANT-A", "Record-7"), ("tenant-a ", "Record-7"),
            ("tenant-a", "record-7"), ("tenant-a", "Record-7 "), ("tenant-a", "operation-a") })
            Assert.Null(await reopened.FindAsync(tenant, id));
        Assert.True(MemoryMarshal.TryGetArray(row.Body, out var bytes));
        bytes.Array![bytes.Offset] = (byte)'!';
        Assert.Equal("{\"value\":\"A\"}", Encoding.UTF8.GetString((await reopened.FindAsync(Tenant, "Record-7"))!.Body.Span));
        Assert.Equal(2, Entries().Count);
    }

    [Theory]
    [InlineData("rollback")]
    [InlineData("dispose")]
    [InlineData("cancel")]
    [InlineData("incomplete")]
    public async Task staged_rolled_back_cancelled_and_failed_transactions_are_not_current_rows(string end)
    {
        var store = new FileJournalRecordWriteStore(PathName);
        await using (var transaction = await Stage(store, Row("Record-7", "operation-a", new("schema:fixture")),
            audit: end != "incomplete"))
        {
            Assert.Null(await store.FindAsync(Tenant, "Record-7"));
            if (end == "rollback") await transaction.RollbackAsync();
            if (end == "cancel")
            {
                using var cancelled = new CancellationTokenSource();
                cancelled.Cancel();
                await Assert.ThrowsAnyAsync<OperationCanceledException>(() => transaction.CommitAsync(cancelled.Token).AsTask());
            }
            if (end == "incomplete")
                await Assert.ThrowsAsync<InvalidOperationException>(() => transaction.CommitAsync().AsTask());
        }
        Assert.Null(await new FileJournalRecordWriteStore(PathName).FindAsync(Tenant, "Record-7"));
        Assert.False(File.Exists(PathName));
    }

    [Fact]
