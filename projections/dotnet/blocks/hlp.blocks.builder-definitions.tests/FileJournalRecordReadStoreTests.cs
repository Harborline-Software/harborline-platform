    [Fact]
    public async Task literal_predecessor_schema_binds_successfully_after_reopen_with_a_fresh_registry_without_rewriting_evidence()
    {
        var fixture = await Published();
        var old = await fixture.Registry.RegisterAsync(OldScalarSchema);
        var document = RecordTypeDefinitionJson.Deserialize(Encoding.UTF8.GetBytes(TypeJson)).ToDefinition();
        var predecessor = await fixture.Compiler.CompilePreT616ScalarForStoredReadAsync(document, null);
        Assert.Empty(predecessor.Refusals);
        Assert.Equal(OldScalarSchema, predecessor.JsonSchemaText);
        var current = (await fixture.Records.ResolvePublishedSchemaAsync(Tenant, TypeId, "1.0.0"))!;
        Assert.NotEqual(old.Id, current.Schema.Id);
        Assert.True((await fixture.Registry.ValidateAsync(old.Id, Encoding.UTF8.GetBytes("{\"value\":\"A\"}"))).IsValid);
        Assert.False((await fixture.Registry.ValidateAsync(old.Id, Encoding.UTF8.GetBytes("{\"value\":[\"A\"]}"))).IsValid);
        Assert.True((await fixture.Registry.ValidateAsync(current.Schema.Id, Encoding.UTF8.GetBytes("{\"value\":[\"A\"]}"))).IsValid);
        var store = new FileJournalRecordWriteStore(PathName);
        await using var transaction = await Stage(store, Row("legacy-record", "legacy-write", old.Id));
        var original = (await transaction.CommitAsync()).Receipt!;
        var before = File.ReadAllBytes(PathName);
        var reader = Reader(fixture, new FileJournalRecordWriteStore(PathName));
        Assert.Null(await reader.Registry.GetAsync(old.Id)); // Compatibility must work after registry restart.

        var outcome = await reader.Operation.ReadAsync(new(Tenant, Actor), new("legacy-record"));

        var record = Assert.IsType<RecordReadResult>(outcome.Record);
        Assert.Equal(old.Id, record.Schema);
        Assert.Equal("1.0.0", record.Version);
        Assert.Equal(TypeDigest, record.DefinitionDigest);
        Assert.Equal("{\"value\":\"A\"}", Encoding.UTF8.GetString(record.Body.Span));
        Assert.Equal(new DateTimeOffset(2026, 2, 3, 4, 5, 6, TimeSpan.Zero), record.RecordedAt);
        Assert.Equal(OldScalarSchema, (await reader.Registry.GetAsync(old.Id))!.JsonSchemaText);
        Assert.Equal(original, (await store.FindAsync(new RecordWriteOperationKey(Tenant, Actor, "legacy-write")))!.Receipt);
        Assert.Equal(before, File.ReadAllBytes(PathName));
        Assert.Single(Entries());
    }

    [Fact]
    public async Task predecessor_receipt_replay_and_conflict_never_rebind_or_rewrite_but_new_writes_use_corrected_schema()
    {
        var fixture = await Published();
        var old = await fixture.Registry.RegisterAsync(OldScalarSchema);
        var store = new FileJournalRecordWriteStore(PathName);
        await using var transaction = await Stage(store, Row("legacy-record", "legacy-write", old.Id));
        var original = (await transaction.CommitAsync()).Receipt!;
        var before = File.ReadAllBytes(PathName);
        var events = new List<string>();
        var observed = new Catalogue(fixture.Catalogue, events) { FailOnBinding = true };
        var records = new RecordTypeDefinitionStore(observed, fixture.Compiler, fixture.Defaults, fixture.Registry, Window,
            roles: CreationRoles);
        var gate = new Gate(events);
        var writer = new RecordWriteOperation(new AccessProvider(gate), records, fixture.Registry, store, store,
            new Clock(Now), fixture.Kinds, fixture.Domains);

        var replay = await writer.CreateAsync(new(Tenant, Actor), new(TypeId, "legacy-write", JsonNode.Parse("{\"value\":\"A\"}")!.AsObject()));

        Assert.True(replay.Committed);
        Assert.True(replay.Replayed);
        Assert.Equal(original, replay.Receipt);
        Assert.Equal(old.Id, replay.Receipt!.Schema);
        Assert.Same(Assert.Single(gate.Decisions), replay.Decision);
        Assert.Equal(new DateTimeOffset(2030, 1, 2, 3, 4, 5, TimeSpan.Zero), replay.Decision!.At);
        Assert.Equal(["authorize"], events);
        Assert.Equal(before, File.ReadAllBytes(PathName));
        var conflict = await writer.CreateAsync(new(Tenant, Actor), new(TypeId, "legacy-write", JsonNode.Parse("{\"value\":\"B\"}")!.AsObject()));
        Assert.Equal("records.write.replay_conflict", conflict.Refusal!.Code);
        Assert.Equal(["/operation_id"], conflict.Refusal.Pointers);
        Assert.Null(conflict.Receipt);
        Assert.Equal(before, File.ReadAllBytes(PathName));
        Assert.Single(Entries());
        Assert.Equal(0, observed.HeadReads);
        Assert.Empty(observed.Pins);

        var created = await Writer(fixture, store, new Gate([])).CreateAsync(new(Tenant, Actor),
            new(TypeId, "new-write", JsonNode.Parse("{\"value\":[\"A\"]}")!.AsObject()));
        Assert.True(created.Committed);
        Assert.False(created.Replayed);
        Assert.NotEqual(old.Id, created.Receipt!.Schema);
        Assert.Equal((await fixture.Records.ResolvePublishedSchemaAsync(Tenant, TypeId, "1.0.0"))!.Schema.Id, created.Receipt.Schema);
        Assert.Equal(2, Entries().Count);
        Assert.Equal(old.Id, (await store.FindAsync(Tenant, "legacy-record"))!.Schema);
    }

    [Theory]
    [InlineData("digest")]
    [InlineData("registered-schema")]
    [InlineData("unknown-schema")]
    [InlineData("version")]
    public async Task stored_binding_never_accepts_digest_only_registry_membership_or_a_head_in_place_of_an_exact_version(string poison)
    {
        var fixture = await Published();
        var old = await fixture.Registry.RegisterAsync(OldScalarSchema);
        var unrelated = await fixture.Registry.RegisterAsync("{\"type\":\"object\"}");
        var row = Row("legacy-record", "legacy-write", old.Id);
        row = poison switch
        {
            "digest" => row with { DefinitionDigest = new string('f', 64) },
            "registered-schema" => row with { Schema = unrelated.Id },
            "unknown-schema" => row with { Schema = new("schema:unrelated-not-registered") },
            "version" => row with { Version = "9.0.0" },
            _ => throw new InvalidOperationException("Unknown literal binding fixture."),
        };
        var store = new FileJournalRecordWriteStore(PathName);
        await using var transaction = await Stage(store, row);
        await transaction.CommitAsync();
        var before = File.ReadAllBytes(PathName);
        var reader = Reader(fixture, store);
        await reader.Registry.RegisterAsync("{\"type\":\"object\"}");
        if (poison == "version")
        {
            var outcome = await reader.Operation.ReadAsync(new(Tenant, Actor), new("legacy-record"));
            Assert.Null(outcome.Record);
            Assert.Equal("entity.validation.schema_unknown", outcome.Refusal);
            Assert.Same(Assert.Single(reader.Gate.Decisions), outcome.Decision);
        }
        else await Assert.ThrowsAsync<InvalidDataException>(() => reader.Operation.ReadAsync(new(Tenant, Actor), new("legacy-record")).AsTask());
        Assert.Equal(["lookup", "authorize", "bind"], reader.Events);
        Assert.Equal(0, reader.Catalogue.HeadReads);
        Assert.Equal(before, File.ReadAllBytes(PathName));
    }

    private static RecordWriteRow Row(string recordId, string operationId, SchemaId schema)
        => new(Tenant, recordId, TypeId, "1.0.0", TypeDigest, schema, Actor, operationId, null,
            "records-write-intent/1", ScalarIntentDigest, Encoding.UTF8.GetBytes("{\"value\":\"A\"}"), Recorded);

    private static async Task<IKernelPreparedTransaction<RecordWriteRow, RecordWriteCommit>> Stage(
        FileJournalRecordWriteStore store, RecordWriteRow row, bool audit = true)
    {
        var key = new RecordWriteOperationKey(row.Tenant, Actor, row.OperationId);
        var transaction = await store.BeginAsync();
        await transaction.StageOperationAsync(new(row.RecordId, key.IdempotencyKey, row.IntentDigest));
        await transaction.StageRecordAsync(row);
        if (audit) await transaction.StageAuditAsync(new("audit-" + row.OperationId, Actor, Recorded, Encoding.UTF8.GetBytes("{}")));
        return transaction;
    }

    private JsonArray Entries() => JsonNode.Parse(File.ReadAllText(PathName))!["Entries"]!.AsArray();

    private sealed record DefinitionFixture(InMemoryVersionedDefinitionStore Catalogue, RecordTypeDefinitionStore Records,
        RecordTypeSchemaCompiler Compiler, InMemorySchemaRegistry Registry, RecordFieldDefaults Defaults,
        IFieldKindRuntime Kinds, IFieldDomainRuntime Domains);

    private static async Task<DefinitionFixture> Published()
    {
        var host = Host(); // Real shared catalogue and a freshly published eam.equipment Class.
        var kinds = RecordWriteFieldRuntimeTests.FixtureKinds();
        var domains = RecordWriteFieldRuntimeTests.FixtureDomains(new Clock(Recorded));
        var compiler = new RecordTypeSchemaCompiler(new RecordsIntentValidator(), kinds, new SharedValueDomainAdmission(), domains);
        var registry = new InMemorySchemaRegistry(fieldKindRuntime: kinds);
        var defaults = new RecordFieldDefaults(kinds);
        var records = new RecordTypeDefinitionStore(host.Catalogue, compiler, defaults, registry, Window, roles: CreationRoles);
        await host.Catalogue.SaveDraftAsync(new(new(Tenant, DefinitionKind.Records, TypeId), "1.0.0", "1.0.0", TypeJson), 0, "reading-draft");
        var publication = await records.PublishAsync(Tenant, TypeId, "1.0.0", 1, "reading-publish");
        Assert.Equal(TypeDigest, publication.Revision.Digest);
        return new(host.Catalogue, records, compiler, registry, defaults, kinds, domains);
    }

    private static RecordWriteOperation Writer(DefinitionFixture fixture, FileJournalRecordWriteStore store, Gate gate)
        => new(new AccessProvider(gate), fixture.Records, fixture.Registry, store, store, new Clock(Recorded), fixture.Kinds, fixture.Domains);

    private sealed record ReadFixture(RecordReadOperation Operation, Gate Gate, Catalogue Catalogue,
        InMemorySchemaRegistry Registry, Clock Clock, List<string> Events);

    private static ReadFixture Reader(DefinitionFixture fixture, IRecordReadStore store)
    {
        var events = new List<string>();
        var catalogue = new Catalogue(fixture.Catalogue, events);
        var registry = new InMemorySchemaRegistry(fieldKindRuntime: fixture.Kinds);
        var records = new RecordTypeDefinitionStore(catalogue, fixture.Compiler, fixture.Defaults, registry, Window, roles: CreationRoles);
        var gate = new Gate(events);
        var clock = new Clock(Now);
        return new(new(new ReaderObservation(store, events), new AccessProvider(gate), records, clock), gate, catalogue, registry, clock, events);
    }

    private sealed class ReaderObservation(IRecordReadStore inner, List<string> events) : IRecordReadStore
    {
        public ValueTask<RecordWriteRow?> FindAsync(string tenant, string recordId, CancellationToken cancellationToken = default)
        { events.Add("lookup"); return inner.FindAsync(tenant, recordId, cancellationToken); }
    }

    private sealed class Gate(List<string> events) : IAuthorizationDecider
    {
        public bool Allow { get; set; } = true;
        public List<AccessRequest> Requests { get; } = [];
        public List<AuthorizationDecisionEvidence> Decisions { get; } = [];
        public ValueTask<AuthorizationDecisionEvidence> DecideAsync(AccessRequest request, CancellationToken cancellationToken = default)
        {
            cancellationToken.ThrowIfCancellationRequested();
            events.Add("authorize"); Requests.Add(request);
            var decision = new AuthorizationDecisionEvidence(request, Allow, Allow ? "None" : "ReadDenied", "grant:fixture@1", [], []);
            Decisions.Add(decision);
            return ValueTask.FromResult(decision);
        }
    }

    private sealed class Clock(DateTimeOffset instant) : TimeProvider
    {
        public int Reads { get; private set; }
        public override DateTimeOffset GetUtcNow() { Reads++; return instant; }
    }

    private sealed class Catalogue(IVersionedDefinitionStore inner, List<string> events) : IVersionedDefinitionStore
    {
        public bool FailOnBinding { get; init; }
        public int HeadReads { get; private set; }
        public List<DefinitionBinding> Pins { get; } = [];
        public ValueTask<IReadOnlyList<DefinitionKey>> ListKeysAsync(string tenant, DefinitionKind kind, CancellationToken cancellationToken = default)
            => inner.ListKeysAsync(tenant, kind, cancellationToken);
        public ValueTask<DefinitionRevision> SaveDraftAsync(DefinitionDocument document, long expectedRevision, string requestId,
            CancellationToken cancellationToken = default) => inner.SaveDraftAsync(document, expectedRevision, requestId, cancellationToken);
        public ValueTask<DefinitionRevision> PublishAsync(DefinitionKey key, string versionId, long expectedRevision, string requestId,
            CancellationToken cancellationToken = default) => inner.PublishAsync(key, versionId, expectedRevision, requestId, cancellationToken);
        public ValueTask<DefinitionRevision> RestoreAsDraftAsync(DefinitionKey key, string sourceVersionId, string draftVersionId,
            string draftVersion, long expectedRevision, string requestId, CancellationToken cancellationToken = default)
            => inner.RestoreAsDraftAsync(key, sourceVersionId, draftVersionId, draftVersion, expectedRevision, requestId, cancellationToken);
        public ValueTask<IReadOnlyList<DefinitionRevision>> ListHistoryAsync(DefinitionKey key, CancellationToken cancellationToken = default)
            => inner.ListHistoryAsync(key, cancellationToken);
        public ValueTask<DefinitionRevision?> GetPublishedHeadAsync(DefinitionKey key, CancellationToken cancellationToken = default)
        {
            if (key.Kind == DefinitionKind.Records) { HeadReads++; if (FailOnBinding) throw new InvalidOperationException("Replay rebound."); }
            return inner.GetPublishedHeadAsync(key, cancellationToken);
        }
        public ValueTask<DefinitionRevision?> ResolvePublishedAsync(DefinitionBinding binding, CancellationToken cancellationToken = default)
        {
            if (binding.Key.Kind == DefinitionKind.Records)
            {
                if (FailOnBinding) throw new InvalidOperationException("Replay rebound.");
                events.Add("bind"); Pins.Add(binding);
            }
            return inner.ResolvePublishedAsync(binding, cancellationToken);
        }
    }

    public void Dispose() { if (Directory.Exists(_directory)) Directory.Delete(_directory, recursive: true); }
