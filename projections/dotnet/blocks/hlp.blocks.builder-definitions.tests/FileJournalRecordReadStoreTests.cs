    [Fact]
    public async Task actual_current_write_reopen_and_read_preserve_gate_order_binding_bytes_and_original_instant()
    {
        var fixture = await Published();
        var store = new FileJournalRecordWriteStore(PathName);
        var write = await Writer(fixture, store, new Gate([])).CreateAsync(new(Tenant, Actor),
            new(TypeId, "actual-write", JsonNode.Parse("{\"value\":[\"A\"]}")!.AsObject()));
        Assert.True(write.Committed);
        var receipt = Assert.IsType<RecordWriteReceipt>(write.Receipt);
        var before = File.ReadAllBytes(PathName);
        var reader = Reader(fixture, new FileJournalRecordWriteStore(PathName));

        var outcome = await reader.Operation.ReadAsync(new(Tenant, Actor), new(receipt.RecordId));

        var record = Assert.IsType<RecordReadResult>(outcome.Record);
        Assert.Equal("{\"value\":[\"A\"]}", Encoding.UTF8.GetString(record.Body.Span));
        Assert.Equal("eam.reading", record.RecordTypeId);
        Assert.Equal("1.0.0", record.Version);
        Assert.Equal(TypeDigest, record.DefinitionDigest);
        Assert.Equal(receipt.Schema, record.Schema);
        Assert.Equal(new DateTimeOffset(2026, 2, 3, 4, 5, 6, TimeSpan.Zero), record.RecordedAt);
        Assert.Equal(["lookup", "authorize", "bind"], reader.Events);
        Assert.Equal(1, reader.Clock.Reads);
        var request = Assert.Single(reader.Gate.Requests);
        Assert.Equal(("records:read", "operator-7", "tenant-a", "record", receipt.RecordId, "eam.reading"),
            (request.Operation, request.Principal, request.Tenant, request.Record.Kind, request.Record.Id, request.Record.RecordTypeId));
        Assert.Equal(new DateTimeOffset(2030, 1, 2, 3, 4, 5, TimeSpan.Zero), request.At);
        Assert.Equal("A", request.Record.Fields["value"]![0]!.GetValue<string>());
        Assert.Equal(0, reader.Catalogue.HeadReads);
        Assert.Equal("1.0.0", Assert.Single(reader.Catalogue.Pins).VersionId);
        Assert.Equal(before, File.ReadAllBytes(PathName));
    }

    [Fact]
