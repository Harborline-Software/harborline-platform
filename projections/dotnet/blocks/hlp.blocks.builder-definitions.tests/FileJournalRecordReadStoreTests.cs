        await fixture.Catalogue.RestoreAsDraftAsync(key, "1.0.0", "1.0.2", "1.0.2", 2, "restore-identical");
        var restored = await fixture.Records.PublishAsync(Tenant, TypeId, "1.0.2", 3, "publish-identical");
