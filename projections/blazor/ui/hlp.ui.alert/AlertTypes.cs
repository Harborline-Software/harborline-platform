namespace Harborline.UIAdapters.Blazor.Components.Feedback;
/// <summary>The severity styling and icon of an alert.</summary>
public enum AlertVariant
{
    /// <summary>Shows the alert as neutral information.</summary>
    Info,
    /// <summary>Shows the alert as a completed or successful outcome.</summary>
    Success,
    /// <summary>Shows the alert as a caution the user should heed.</summary>
    Warning,
    /// <summary>Shows the alert as a failure that needs action.</summary>
    Error
}
