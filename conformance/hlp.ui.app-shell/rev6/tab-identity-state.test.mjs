import test from 'node:test'
import assert from 'node:assert/strict'
import { initialState, transition, presentation, runScenario } from '../../../projections/shared/ui/hlp.ui.app-shell/rev6/tab-identity-state.mjs'
const owner = { person: 'alice', tenant: 'north', workspace: 'work' }
const start = () => transition(initialState(), { type: 'identity', owner })
const open = (state, target, preview = false, kind = 'Details') => transition(state, { type: 'open', kind, target, preview })
const id = '["Details","record-a"]' // literal stable identity oracle, independent of production key builder

test('P4/P9: destination closes only clean preview; permanent, kept and pinned survive', () => {
 let state = open(start(), 'record-a', true)
 state = transition(state, { type: 'keep', id })
 state = open(state, 'record-b', true)
 state = transition(state, { type: 'pin', id: '["Details","record-b"]' })
 state = open(state, 'record-c')
 state = open(state, 'record-d', true)
 state = transition(state, { type: 'navigate', destination: 'other' })
 assert.deepEqual(presentation(state).tabs.map(t => t.target), ['record-a', 'record-b', 'record-c'])
})
test('P1: kind plus target dedupes and separate Assistant conversations remain separate', () => {
 let state = open(open(start(), 'conversation-a', false, 'Assistant'), 'conversation-b', false, 'Assistant')
 state = open(state, 'conversation-a', true, 'Assistant')
 assert.equal(presentation(state).tabs.length, 2)
 assert.equal(presentation(state).active, '["Assistant","conversation-a"]')
})
test('editing promotes preview and same-person navigation preserves exact dirty draft', () => {
 const before = open(start(), 'record-a', true)
 let state = transition(before, { type: 'edit', id, draft: 'unsaved text' })
 state = transition(state, { type: 'navigate', destination: 'other' })
 assert.deepEqual(presentation(state).tabs[0], { id, kind: 'Details', target: 'record-a', preview: false, pinned: false, dirty: true })
 assert.equal(presentation(state).drafts[id], 'unsaved text')
 assert.equal(presentation(before).tabs[0].preview, true)
})
test('destruction Cancel preserves; Save waits for acknowledgment; Discard removes', () => {
 const dirty = runScenario([{ type: 'identity', owner }, { type: 'open', kind: 'Details', target: 'record-a', preview: true }, { type: 'edit', id, draft: 'draft' }, { type: 'close', id }])
 assert.equal(presentation(dirty).pendingClose, id)
 const canceled = transition(dirty, { type: 'resolve-close', choice: 'cancel' })
 assert.equal(presentation(canceled).tabs.length, 1)
 assert.equal(presentation(canceled).pendingClose, null)
 const saving = transition(dirty, { type: 'resolve-close', choice: 'save' })
 assert.equal(presentation(saving).drafts[id], 'draft')
 assert.equal(presentation(saving).tabs.length, 1)
 assert.equal(presentation(transition(saving, { type: 'saved', owner, id, requestId: 1, generation: 1 })).tabs.length, 0)
 const discarded = presentation(transition(dirty, { type: 'resolve-close', choice: 'discard' }))
 assert.equal(discarded.tabs.length, 0)
 assert.deepEqual(discarded.drafts, {})
})
test('tenant/person/workspace boundary hides private presentation, retains owner work; sign-out has no work effects', () => {
 let state = transition(open(start(), 'record-a'), { type: 'edit', id, draft: 'private draft' })
 state = transition(state, { type: 'retain', id: 'cache', cache: { private: true }, action: { id: 'queued-write' } })
 const retained = structuredClone(state.owners)
 for (const changed of [{ ...owner, tenant: 'south' }, { ...owner, person: 'bob' }, { ...owner, workspace: 'other' }]) {
  const switched = transition(state, { type: 'identity', owner: changed })
  assert.deepEqual(presentation(switched).tabs, [])
  assert.deepEqual(presentation(switched).drafts, {})
  assert.deepEqual(presentation(switched).queuedActions, [])
  assert.deepEqual(presentation(transition(switched, { type: 'identity', owner })).drafts, { [id]: 'private draft' })
 }
 const signedOut = transition(state, { type: 'sign-out' })
 assert.equal(presentation(signedOut), null)
 assert.deepEqual(signedOut.owners, retained)
})
