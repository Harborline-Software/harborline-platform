test('late Alice save acknowledgment never destroys Bob same-address dirty editor', () => {
 const makeDirty = state => transition(open(state, 'record-a'), { type: 'edit', id, draft: 'owner draft' })
 let state = transition(makeDirty(start()), { type: 'close', id })
 state = transition(state, { type: 'resolve-close', choice: 'save' })
 assert.deepEqual(presentation(state).saveRequest, { owner, id, generation: 1, requestId: 1 })
 const bob = { person: 'bob', tenant: 'north', workspace: 'work' }
 state = transition(state, { type: 'identity', owner: bob })
 state = transition(makeDirty(state), { type: 'close', id })
 state = transition(state, { type: 'resolve-close', choice: 'save' })
 assert.equal(presentation(state).saveRequest.requestId, 2)
 state = transition(state, { type: 'saved', owner, id, requestId: 1, generation: 1 })
 assert.equal(presentation(state).tabs.length, 1)
 assert.equal(presentation(state).drafts[id], 'owner draft')
 assert.equal(presentation(state).pendingClose, id)
 assert.equal(presentation(state).saveRequest.requestId, 2)
 const alice = transition(state, { type: 'identity', owner })
 assert.equal(presentation(alice).tabs.length, 0)
 assert.deepEqual(presentation(alice).drafts, {})
})
test('stale same-owner save cannot destroy a later draft generation or canceled close', () => {
 let state = transition(open(start(), 'record-a'), { type: 'edit', id, draft: 'first' })
 state = transition(state, { type: 'close', id })
 state = transition(state, { type: 'resolve-close', choice: 'save' })
 state = transition(state, { type: 'edit', id, draft: 'second' })
 state = transition(state, { type: 'resolve-close', choice: 'save' })
 assert.deepEqual(presentation(state).saveRequest, { owner, id, generation: 2, requestId: 2 })
 state = transition(state, { type: 'saved', owner, id, requestId: 1, generation: 1 })
 assert.equal(presentation(state).drafts[id], 'second')
 state = transition(state, { type: 'resolve-close', choice: 'cancel' })
 state = transition(state, { type: 'saved', owner, id, requestId: 2, generation: 2 })
 assert.equal(presentation(state).tabs.length, 1)
 assert.equal(presentation(state).drafts[id], 'second')
})

test('one close modal preserves A save request when B close is requested', () => {
 const secondId = '["Details","record-b"]'
 let state = transition(open(start(), 'record-a'), { type: 'edit', id, draft: 'A draft' })
 state = transition(open(state, 'record-b'), { type: 'edit', id: secondId, draft: 'B draft' })
 state = transition(state, { type: 'close', id })
 state = transition(state, { type: 'resolve-close', choice: 'save' })
 state = transition(state, { type: 'close', id: secondId })
 state = transition(state, { type: 'resolve-close', choice: 'save' })
 assert.equal(presentation(state).pendingClose, id)
 assert.deepEqual(presentation(state).saveRequest, { owner, id, generation: 1, requestId: 1 })
 state = transition(state, { type: 'saved', owner, id, generation: 1, requestId: 1 })
 assert.deepEqual(presentation(state).tabs.map(tab => tab.target), ['record-b'])
 assert.equal(presentation(state).drafts[secondId], 'B draft')
 state = transition(state, { type: 'close', id: secondId })
 state = transition(state, { type: 'resolve-close', choice: 'save' })
 assert.deepEqual(presentation(state).saveRequest, { owner, id: secondId, generation: 1, requestId: 2 })
 state = transition(state, { type: 'saved', owner, id: secondId, generation: 1, requestId: 2 })
 assert.deepEqual(presentation(state).tabs, [])
 assert.deepEqual(presentation(state).drafts, {})
})

test('editing B preserves pending A save correlation and acknowledges only A', () => {
 const secondId = '["Details","record-b"]'
 let state = transition(open(start(), 'record-a'), { type: 'edit', id, draft: 'A draft' })
 state = open(state, 'record-b')
 state = transition(state, { type: 'close', id })
 state = transition(state, { type: 'resolve-close', choice: 'save' })
 state = transition(state, { type: 'edit', id: secondId, draft: 'B newer draft' })
 assert.deepEqual(presentation(state).saveRequest, { owner, id, generation: 1, requestId: 1 })
 assert.equal(presentation(state).pendingClose, id)
 state = transition(state, { type: 'saved', owner, id, generation: 1, requestId: 1 })
 assert.deepEqual(presentation(state).tabs.map(tab => tab.target), ['record-b'])
 assert.deepEqual(presentation(state).drafts, { [secondId]: 'B newer draft' })
 assert.equal(presentation(state).tabs[0].dirty, true)
 assert.equal(presentation(state).pendingClose, null)
 assert.equal(presentation(state).saveRequest, null)
})
