using System.Globalization;
using System.Text;
using Harborline.Foundation.Definitions;

namespace Harborline.Tooling.ContentKinds;

/// <summary>Deterministic generation and read-only byte comparison for checked-in pack identities.</summary>
public static class Generator
{
    /// <summary>Renders only explicitly declared constants using the supplied registry and export.</summary>
    public static IReadOnlyDictionary<string, byte[]> Generate(
        IReadOnlyList<PackContentKindEntry> kinds, IReadOnlyList<PackPillarEntry> pillars,
        byte[] export, IReadOnlyList<IdentityDeclaration> declarations)
    {
        var outputs = new SortedDictionary<string, byte[]>(StringComparer.Ordinal)
        {
            ["_shared/content-kinds/content-kinds.json"] = export,
        };
        foreach (var declaration in declarations.OrderBy(row => row.Path, StringComparer.Ordinal))
        {
            var text = new StringBuilder("// <auto-generated />\n// Regenerate: dotnet run --project tooling/content-kind-export -- --root .\nusing Harborline.Foundation.Definitions;\n\n");
            text.Append("namespace ").Append(declaration.Namespace).Append(";\n\npublic static partial class ").Append(declaration.Type).Append("\n{\n");
            foreach (var constant in declaration.Constants.OrderBy(row => row.Name, StringComparer.Ordinal))
            {
                if (string.IsNullOrWhiteSpace(constant.Documentation))
                    throw new InvalidDataException($"Missing documentation: {declaration.Type}.{constant.Name}");
                var value = constant.IsPillar
                    ? pillars.Single(row => row.Name == constant.RegistryName).Value
                    : kinds.Single(row => row.Name == constant.RegistryName).Value;
                foreach (var line in constant.Documentation.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n'))
                    text.Append("    /// ").Append(line).Append('\n');
                text.Append("    public const int ").Append(constant.Name).Append(" = ").Append(value.ToString(CultureInfo.InvariantCulture)).Append(";\n");
            }
            text.Append("}\n");
            outputs.Add(declaration.Path, Encoding.UTF8.GetBytes(text.ToString()));
        }
        return outputs;
    }

    /// <summary>Checks every output without writing, or writes the generated bytes. Returns all differing paths.</summary>
    public static IReadOnlyList<string> Apply(string root, IReadOnlyDictionary<string, byte[]> outputs, bool check)
    {
        var differences = new List<string>();
        foreach (var (relative, bytes) in outputs.OrderBy(pair => pair.Key, StringComparer.Ordinal))
        {
            var path = Path.Combine(root, relative);
            if (check)
            {
                if (!File.Exists(path) || !File.ReadAllBytes(path).AsSpan().SequenceEqual(bytes)) differences.Add(relative);
            }
            else
            {
                Directory.CreateDirectory(Path.GetDirectoryName(path)!);
                File.WriteAllBytes(path, bytes);
            }
        }
        return differences;
    }
}
