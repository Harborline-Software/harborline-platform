using Harborline.Foundation.Definitions;
using Harborline.Tooling.ContentKinds;
using Xunit;

namespace Harborline.Tooling.ContentKinds.Tests;

public sealed class GeneratorTests
{
    private static readonly PackContentKindEntry[] Kinds = [new("Fixture", 42, "FixturePillar", PackContentKindStatus.Reserved), new("Unlisted", 43, "FixturePillar", PackContentKindStatus.Shipped)];
    private static readonly PackPillarEntry[] Pillars = [new("FixturePillar", 77)];
    private static IdentityDeclaration Identity(string documentation = "<summary>Fixture documentation.</summary>") => new("Fixture.g.cs", "FixtureNamespace", "FixturePackIdentity", [new("ContentKind", "Fixture", false, documentation), new("Primitive", "FixturePillar", true, documentation)]);

    [Fact(DisplayName = "T-738/platform-generated-pack-identities A4 A6 A9 fixture literals and unlisted kind")]
    public void Fixture_renders_only_declared_documented_constants()
    {
        var generated = Generator.Generate(Kinds, Pillars, [10], [Identity()]);
        Assert.Equal(new byte[] {10}, generated["_shared/content-kinds/content-kinds.json"]);
        Assert.Equal("// <auto-generated />\n// Regenerate: dotnet run --project tooling/content-kind-export -- --root .\nusing Harborline.Foundation.Definitions;\n\nnamespace FixtureNamespace;\n\npublic static partial class FixturePackIdentity\n{\n    /// <summary>Fixture documentation.</summary>\n    public const int ContentKind = 42;\n    /// <summary>Fixture documentation.</summary>\n    public const int Primitive = 77;\n}\n", System.Text.Encoding.UTF8.GetString(generated["Fixture.g.cs"]));
        Assert.Equal(2, generated.Count);
    }

    [Theory(DisplayName = "T-738/platform-generated-pack-identities A6 A9 documentation required")]
    [InlineData("")]
    [InlineData("  ")]
    public void Missing_documentation_is_refused(string documentation) => Assert.Throws<InvalidDataException>(() => Generator.Generate(Kinds, Pillars, [], [Identity(documentation)]));

    [Fact(DisplayName = "T-738/platform-generated-pack-identities A9 fixture changed value fails check and names file")]
    public void Fixture_check_is_read_only_and_lists_all_differences()
    {
        var scratch = Path.Combine(Path.GetTempPath(), "harborline", "t738-packids", Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(scratch);
        var outputs = Generator.Generate(Kinds, Pillars, [10], [Identity()]);
        Assert.Equal(new[] {"Fixture.g.cs", "_shared/content-kinds/content-kinds.json"}, Generator.Apply(scratch, outputs, true));
        Assert.Empty(Directory.GetFiles(scratch));
        Assert.Empty(Generator.Apply(scratch, outputs, false));
        Assert.Empty(Generator.Apply(scratch, outputs, true));
        var changed = Generator.Generate([Kinds[0] with {Value = 41}], Pillars, [10], [Identity()]);
        Assert.Equal(new[] {"Fixture.g.cs"}, Generator.Apply(scratch, changed, true));
        Assert.Empty(Generator.Apply(scratch, outputs, true));
    }
}
